def locate(paths):
    for p in paths:
        q = Path(p)
        if q.exists():
            return q
    return None


def self_test(a: Assets):
    bm = BiosMath(a)

    assert a.score_guardian == 75
    assert a.score_capture == 325
    assert a.score_trophy == 750
    assert len(a.web_script) == 15
    assert len(a.vertex_words) == 8
    assert len(a.motion8) == 7
    assert len(a.motion16) == 7
    assert len(a.motion32) == 7
    assert len(a.trophy_keys) == 40

    assert a.rotation_table == Assets.FALLBACK_ROTATION_TABLE

    # ROM starts speed at trophies+4; with zero trophies speed=4 and
    # table_delays_between_web_lines-1 indexing selects $2A.
    _tmp_game = Game(a)
    _tmp_game.speed = 4
    assert _tmp_game.current_web_delay() == 0x2A

    # $1177 first and last cumulative vertices.
    assert a.vertex_words[0] == (0x3000, 0x5000)
    assert a.vertex_words[-1] == (0x3000, 0xB000)

    # Central segment midpoint = Y -48, X 0.
    mid = a.midpoint(3)
    assert mid == (0xD000, 0x0000)

    # Angle zero: rise is identity, run zero.
    assert bm.transform_pair(-48, 0, 0) == (-48, 0)

    # $094F with zero camera splits -48 into two -24 moves.
    assert build_draw_displacement(0, 0, -48, 0) == ((-24, 0), (-24, 0))

    # Exact rounded depth rule.
    d = advance_depth(0x0280, 4, False)
    assert d == ((0x0280 + (((0x0280 * 4) + 0x80) >> 8)) & 0xFFFF)

    # Movement step table exactly traverses a segment in 32 steps.
    y, x = a.vertex_words[3]
    dy, dx = a.motion8[3]
    for _ in range(32):
        y = u16(y + dy)
        x = u16(x + dx)
    assert (y, x) == a.vertex_words[4]

    # Portrait display contract.
    assert (W, H) == (720, 960)
    assert H > W

    # The $191C web camera script is fixed cartridge data, not random.
    assert a.web_script[0] == (127, 0, 0, 0)
    assert a.web_script[1] == (48, 0, -192, 4)
    assert a.web_script[2] == (48, 0, 0, 8)

    # Display calibration only: original $1177 spans 160 X-units.
    # At scale $E0 and gain 1.0 this should map to exactly 560 logical pixels.
    if abs(HW_TO_PIXELS - BASE_HW_TO_PIXELS) < 1e-12:
        assert abs(160 * 0xE0 * HW_TO_PIXELS - 560.0) < 1e-9

    # $094F exact byte-shift regression:
    # with zero camera and transformed (-48,0), each move is (-24,0).
    assert build_draw_displacement(0, 0, -48, 0) == ((-24, 0), (-24, 0))

    # Odd B value proves ASRB is independent rather than RORB from A carry.
    odd = build_draw_displacement(0, 0, 1, 1)
    assert odd == ((0, 0), (1, 1)), odd

    # Camera pre-move must be present in object placement.
    g = Game(a)
    g.camera_a = 0x1800
    g.camera_b = 0xE800
    g.web_angle_word = 0
    g.hawk.depth = 0xE000
    g.hawk.world_y, g.hawk.world_x = a.midpoint(3)
    cam = g.camera_pre_move((CX, CY))
    assert cam != (CX, CY)
    hp, _, _ = g.object_origin(g.hawk)
    assert hp != (CX, CY)

    # Ring initial positioning: with zero camera the separately transformed
    # first $1177 MOVE must be equivalent to moving to (48,80), not executing
    # that MOVE again inside Draw_VLp.
    g.camera_a = 0
    g.camera_b = 0
    g.web_angle_word = 0
    _p1, _p2 = g.web_initial_vertex_displacement()
    assert _p1 == (24, 40), (_p1, _p2)
    assert _p2 == (24, 40), (_p1, _p2)

    _ring = g.web_ring_points(0x4000)
    assert len(_ring) == 8
    # U is symmetric in Y endpoints under angle 0.
    assert _ring[0][1] == _ring[-1][1]

    # Foreground continuation has eight corresponding endpoints at fixed $E0.
    _front = g.web_ring_points(0xE000)
    assert len(_front) == 8
    # It must extend farther from center than a mid-depth ring.
    _ring_span = max(p[0] for p in _ring) - min(p[0] for p in _ring)
    _front_span = max(p[0] for p in _front) - min(p[0] for p in _front)
    assert _front_span > _ring_span

    # Original-style prefill should start play with several receding rings.
    active_depths = sorted(
        (rec["depth"] for rec in g.web_lines if rec["active"]),
        reverse=True
    )
    assert len(active_depths) >= 4, active_depths
    assert all(hi(d) <= 0xE0 for d in active_depths)

    print("SELF-TEST OK")
    print("title:", a.title)
    print("BIOS rotation table source:", "BIOS ROM" if a.bios is not None else "embedded fallback")
    print("rotation table:", a.rotation_table)
    print("center segment midpoint: Y=$%04X X=$%04X" % mid)
    print("angle 0 transform (-48,0):", bm.transform_pair(-48, 0, 0))
    print("$094F initial player displacement:",
          build_draw_displacement(0, 0, -48, 0))
    print("motion8 segment 3:", tuple(s16(v) for v in a.motion8[3]))
    print("32 steps exactly reach next vertex: OK")
    print("display:", W, "x", H, "(3:4 portrait)")
    print("beam factor:", HW_TO_PIXELS, "(gain %.3f)" % (HW_TO_PIXELS / BASE_HW_TO_PIXELS))
    print("full $E0 web width:", 160 * 0xE0 * HW_TO_PIXELS, "logical px")
    print("$094F independent ASRA/ASRB: OK")
    print("camera pre-move @ $7F: OK")
    print("$1177 initial MOVE separated from Draw_VLp: OK")
    print("$191C web motion script: deterministic, not random")
    print("fixed-$E0 foreground rail continuation: OK")
    print("startup web prefill depths:",
          ["$%04X" % d for d in active_depths])
    print("window line clipping: enabled")
    print("scores:", a.score_guardian, a.score_capture, a.score_trophy)



class Assets:
    FALLBACK_ROTATION_TABLE = [
        0, 25, 50, 74, 98, 121, 142, 162,
        181, 198, 213, 226, 237, 245, 251, 255,
        255, 255, 251, 245, 237, 226, 213, 198,
        181, 162, 142, 121, 98, 74, 50, 25,
    ]

    def __init__(self, rom_path: Path, vectors_path: Path, bios_path: Path | None):
        self.rom = rom_path.read_bytes()
        if len(self.rom) != 0x2000:
            raise ValueError(f"Expected 8192-byte Web Warp ROM, got {len(self.rom)}")

        self.vectors = json.loads(vectors_path.read_text(encoding="utf-8"))

        self.bios = None
        if bios_path is not None and bios_path.exists():
            b = bios_path.read_bytes()
            if len(b) == 0x1000:
                self.bios = b

        if self.bios is not None:
            off = 0xFC6D - 0xF000
            self.rotation_table = list(self.bios[off:off + 32])
        else:
            self.rotation_table = list(self.FALLBACK_ROTATION_TABLE)

        self.copyright, p = read80(self.rom, 0)
        self.title_music = be16(self.rom, p)
        p += 6
        self.title, _ = read80(self.rom, p)
        self.title = self.title.strip()

        self.score_guardian = bcd_word(self.rom, 0x1163)
        self.score_capture = bcd_word(self.rom, 0x1165)
        self.score_trophy = bcd_word(self.rom, 0x1167)

        self.web_delay = list(self.rom[0x118F:0x11A9])
        self.player_angles = [s8(x) for x in self.rom[0x18BB:0x18C2]]

        self.bonus = []
        p = 0x18F2
        for _ in range(6):
            t, p = read80(self.rom, p)
            try:
                self.bonus.append(int(t.strip()))
            except ValueError:
                pass

        # $191C: duration, dA, dB, dWeb
        self.web_script = []
        p = 0x191C
        while p + 6 < len(self.rom):
            duration = self.rom[p]
            if duration == 0:
                break
            self.web_script.append((
                duration,
                be16s(self.rom, p + 1),
                be16s(self.rom, p + 3),
                be16s(self.rom, p + 5),
            ))
            p += 7

        self.trophy_keys = {}
        for key in self.vectors:
            if "_trophy_" in key and "_frame_" in key:
                tail = key.split("_trophy_", 1)[1]
                species = int(tail.split("_frame_", 1)[0])
                frame = int(tail.split("_frame_", 1)[1])
                self.trophy_keys[(species, frame)] = key

        self.player_keys = [
            "1996_player_frame_ptrslot_0",
            "19DC_player_frame_ptrslot_1",
            "1A22_player_frame_ptrslot_2",
            "1A68_player_frame_ptrslot_3",
        ]
        self.dragon_keys = [
            "1ABE_dragon_frame_ptrslot_0",
            "1B01_dragon_frame_ptrslot_1",
            "1B44_dragon_frame_ptrslot_2",
            "1B87_dragon_frame_ptrslot_3",
        ]

        self.build_web_tables()

    def vector(self, key):
        return self.vectors[key]["commands"]

    def trophy(self, species, frame):
        return self.vector(self.trophy_keys[(species % 20, frame & 1)])

    def player(self, frame):
        seq = [0, 1, 2, 3, 2, 1, 0, 0]
        return self.vector(self.player_keys[seq[frame & 7]])

    def dragon(self, frame):
        seq = [0, 1, 2, 3, 2, 1, 0, 0]
        return self.vector(self.dragon_keys[seq[frame & 7]])

    def build_web_tables(self):
        """
        Reconstructs what the ROM builds at:
          CA99 : 8 cumulative (Y,X) 16-bit web vertices
          CA43 : 7 segment vectors * 8
          CA60 : 7 segment vectors * 16
          CA7D : 7 segment vectors * 32
        """
        cmds = self.vector("1177_web_semicircle")

        # First mode record is a MOVE from origin to the first web vertex.
        first = cmds[0]
        y = s8(first["dy"]) << 8
        x = s8(first["dx"]) << 8
        self.vertex_words = [(u16(y), u16(x))]

        draw_deltas = []
        for c in cmds[1:]:
            if not c.get("draw"):
                continue
            dy = s8(c["dy"])
            dx = s8(c["dx"])
            draw_deltas.append((dy, dx))
            y = s16(y + (dy << 8))
            x = s16(x + (dx << 8))
            self.vertex_words.append((u16(y), u16(x)))

        if len(self.vertex_words) != 8 or len(draw_deltas) != 7:
            raise ValueError("Unexpected $1177 Web vector structure")

        self.motion8 = [(u16(dy * 8), u16(dx * 8)) for dy, dx in draw_deltas]
        self.motion16 = [(u16(dy * 16), u16(dx * 16)) for dy, dx in draw_deltas]
        self.motion32 = [(u16(dy * 32), u16(dx * 32)) for dy, dx in draw_deltas]

    def midpoint(self, segment):
        """
        Cartridge $0362 semantics:
          D = endpoint A ; ASRA ; RORB
          push D
          D = endpoint B ; ASRA ; RORB
          ADDD pushed
        i.e. halve EACH signed 16-bit endpoint first, then add.
        """
        a = self.vertex_words[segment]
        b = self.vertex_words[segment + 1]
        return (
            u16(asr16(a[0]) + asr16(b[0])),
            u16(asr16(a[1]) + asr16(b[1])),
        )


# ---------------------------------------------------------------------------
# Exact BIOS rise/run transformation
# ---------------------------------------------------------------------------

class BiosMath:
    def __init__(self, assets: Assets):
        self.tbl = assets.rotation_table

    def get_run_idx(self, angle):
        """
        BIOS F5DB.
        Returns (multiplier, flag).
        """
        a = u8(angle)
        b = 0x80 if (a & 0x20) else 0x00
        idx = a & 0x1F
        if idx == 0x10:
            b = u8(b + 1)
        return self.tbl[idx], b

    def get_rise_idx(self, angle):
        """BIOS F5D9: ADDA #$10 then falls into Get_Run_Idx."""
        return self.get_run_idx(u8(angle + 0x10))

    @staticmethod
    def xform(value, pair):
        """
        BIOS F665 core used by Xform_Run_a / Xform_Rise_a.

        The special flag bit 0 handles the exact +/-1.0 quadrant and avoids
        multiplying by 255. Otherwise use 8x8 MUL with the BIOS's rounding.
        """
        mult, flag = pair
        v = s8(value)

        if flag & 1:
            out = v
            if flag & 0x80:
                out = -out
            return s8(out)

        work_flag = flag
        mag = v
        if mag < 0:
            work_flag = u8(~work_flag)
            mag = -mag
            if mag > 127:
                mag = 128

        prod = (mult * (mag & 0xFF)) & 0xFFFF
        # 6809 MUL: C becomes bit 7 of low result; ADCA #0 performs rounding.
        out = ((prod >> 8) + (1 if (prod & 0x80) else 0)) & 0xFF

        if work_flag & 0x80:
            out = u8(-out)

        return s8(out)

    def transform_pair(self, y, x, angle):
        """
        Web Warp $0CC0:
          outY = Xform_Rise(y) + Xform_Run(x)
          outX = Xform_Rise(x) - Xform_Run(y)
        All outputs are 8-bit signed.
        """
        run = self.get_run_idx(angle)
        rise = self.get_rise_idx(angle)

        oy = s8(self.xform(y, rise) + self.xform(x, run))
        ox = s8(self.xform(x, rise) - self.xform(y, run))
        return oy, ox

    def rotate_delta(self, dy, dx, angle):
        return self.transform_pair(s8(dy), s8(dx), angle)


# ---------------------------------------------------------------------------
# $094F BuildDrawDisplacement
# ---------------------------------------------------------------------------

def build_draw_displacement(camera_a_hi, camera_b_hi, transformed_y, transformed_x):
    """
    Byte-exact transcription of cartridge $094F.

    IMPORTANT:
    The routine uses ASRA on A and ASRB on B separately. It does NOT perform
    a 16-bit ASRA/RORB shift here.

    Returns the two relative (dy,dx) vectors consumed by two Mov_Draw_VL calls.
    """
    ca = u8(camera_a_hi)
    cb = u8(camera_b_hi)
    A = u8(transformed_y)
    B = u8(transformed_x)

    # lda C8A0 / asra
    u0, _ = asr8(ca)
    # ldb C8A2 / asrb
    u1, _ = asr8(cb)

    # std ,u ; suba C8A0 ; subb C8A2 ; std 2,u
    u2, _ = sub8(u0, ca)
    u3, _ = sub8(u1, cb)

    # ldd transformed ; asra ; asrb ; suba ,u ; subb 1,u
    ah, _ = asr8(A)
    bh, _ = asr8(B)
    p1a, _ = sub8(ah, u0)
    p1b, _ = sub8(bh, u1)

    # reload transformed
    # asra ; adca 2,u  -- carry is bit shifted out by ASRA
    ah, carry_a = asr8(A)
    p2a, _ = add8(ah, u2, carry_a)

    # asrb ; adcb 3,u  -- ASRB establishes a NEW carry
    bh, carry_b = asr8(B)
    p2b, _ = add8(bh, u3, carry_b)

    return (s8(p1a), s8(p1b)), (s8(p2a), s8(p2b))




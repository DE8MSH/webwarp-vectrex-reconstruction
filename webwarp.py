    def draw_select(self, r, big, mid):
        r.text(big, "SELECT GAME", (CX, 220), WHITE, True)
        r.text(mid, "1   ONE PLAYER", (CX, 360), MID, True)
        r.text(mid, "2   TWO PLAYERS", (CX, 420), MID, True)

    def draw_hud(self, r, small):
        r.text(small, f"P{self.player_index + 1}  {self.p.score:06d}", (18, 18), WHITE)
        r.text(small, f"LIVES {self.p.lives}", (W - 150, 18), MID)
        r.text(small, f"SPEED {self.speed:03d}", (18, 48), MID)
        r.text(small, f"TROPHY {self.p.trophies & 0x7F:02d}", (W - 160, 48), MID)

        if self.message:
            r.text(small, self.message, (CX, 92), WHITE, True)

    def draw_trophy_room(self, r, big, small):
        room2 = bool(self.p.trophies & 0x80)
        r.text(
            big,
            "TROPHY ROOM 2" if room2 else "TROPHY ROOM",
            (CX, 70),
            WHITE,
            True
        )

        count = self.p.trophies & 0x7F
        max_show = min(count, 32 if self.original_trophy_bug else 20)

        for i in range(max_show):
            row, col = divmod(i, 4)
            origin = (105 + col * 170, 180 + row * 105)

            if i < 20:
                r.original_mode_list(
                    self.a.trophy(i, (self.frame // 12) & 1),
                    origin,
                    10,
                    0,
                    MID
                )
            else:
                # Faithful semantic representation of original out-of-table
                # garbage. Exact garbage decode can be added once Trophy Room
                # list reading is fully transcribed.
                r.original_mode_list(
                    self.a.vector("112C_pattern_x_cross"),
                    origin,
                    8,
                    u8(i * 3),
                    DIM
                )

        r.text(small, "1 / 2 TO EXIT", (CX, H - 55), MID, True)

    def draw_gameover(self, r, big, mid):
        r.text(big, "GAME OVER", (CX, 300), WHITE, True)
        r.text(mid, f"PLAYER 1  {self.players[0].score:06d}", (CX, 610), MID, True)
        if self.num_players == 2:
            r.text(mid, f"PLAYER 2  {self.players[1].score:06d}", (CX, 480), MID, True)
        r.text(mid, "R / SPACE", (CX, 610), DIM, True)

    def draw_debug(self, r, tiny):
        if not self.debug:
            return

        origin, transformed, disps = self.object_origin(self.hawk)

        lines = [
            f"BIOS ROT TABLE {'ROM' if self.a.bios is not None else 'EMBEDDED'}",
            f"B5=${self.web_angle_word:04X} angleByte=${self.camera_angle_byte():02X}",
            f"A0=${self.camera_a:04X} A2=${self.camera_b:04X}",
            f"script {self.web_script_i}/{len(self.a.web_script)} t={self.web_script_timer} (deterministic)",
            f"web front rail target=$E000",
            f"hawk seg={self.hawk.segment} sub={self.hawk.subindex:02d}/32",
            f"hawk world Y=${self.hawk.world_y:04X} X=${self.hawk.world_x:04X}",
            f"hawk xform=({transformed[0]:+d},{transformed[1]:+d})",
            f"$094F disp={disps[0]} {disps[1]}",
            f"origin=({origin[0]:.1f},{origin[1]:.1f}) depth=${self.hawk.depth:04X}",
            f"speed={self.speed} webdelay={self.current_web_delay():02X}",
            f"web lines={sum(x['active'] for x in self.web_lines)}/9",
            f"guardians={sum(g.active and g.state>0 for g in self.guardians)}/6",
            f"shots={sum(s.active for s in self.shots)}/9 rod={self.hawk_rod_timer}/13",
        ]

        y = 88
        for line in lines:
            r.text(tiny, line, (10, y), DIM)
            y += 17

    def draw(self, screen, fonts, keys):
        r = Renderer(screen, self.bm)
        big, mid, small, tiny = fonts

        if self.state == "TITLE":
            self.draw_title(r, big, mid, small, keys)

        elif self.state == "SELECT":
            self.draw_select(r, big, mid)

        elif self.state == "PLAY":
            self.draw_web(r)
            self.draw_shots(r)
            self.draw_guardians(r)
            self.draw_creature(r)
            self.draw_portal(r)
            self.draw_dragon(r)
            self.draw_hawk(r)
            self.draw_hud(r, small)
            self.draw_debug(r, tiny)

        elif self.state == "TROPHY":
            self.draw_trophy_room(r, big, small)

        elif self.state == "GAMEOVER":
            self.draw_gameover(r, big, mid)

        if self.paused:
            r.text(big, "PAUSED", (CX, CY), WHITE, True)



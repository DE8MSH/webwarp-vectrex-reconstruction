# ---------------------------------------------------------------------------
# 6809-width helpers
# ---------------------------------------------------------------------------

def u8(v): return v & 0xFF


def s8(v):
    v &= 0xFF
    return v - 0x100 if v & 0x80 else v


def u16(v): return v & 0xFFFF


def s16(v):
    v &= 0xFFFF
    return v - 0x10000 if v & 0x8000 else v


def hi(v): return (v >> 8) & 0xFF


def lo(v): return v & 0xFF


def clamp(v, a, b): return max(a, min(b, v))


def be16(buf, p):
    return (buf[p] << 8) | buf[p + 1]


def be16s(buf, p):
    return int.from_bytes(buf[p:p + 2], "big", signed=True)


def bcd_word(buf, p):
    v = be16(buf, p)
    ds = [(v >> 12) & 15, (v >> 8) & 15, (v >> 4) & 15, v & 15]
    return ds[0] * 1000 + ds[1] * 100 + ds[2] * 10 + ds[3]


def read80(buf, p):
    out = []
    while p < len(buf):
        c = buf[p]
        p += 1
        if c == 0x80:
            break
        out.append(chr(c) if 32 <= c < 127 else " ")
    return "".join(out), p


def neg16(v):
    return u16(-s16(v))


def signed_add16(a, b):
    return u16(s16(a) + s16(b))


def asr8(v):
    """6809 ASR on one byte -> (result, carry)."""
    v = u8(v)
    c = v & 1
    return ((v >> 1) | (v & 0x80)), c


def ror8(v, carry):
    """6809 ROR byte -> (result, carry)."""
    v = u8(v)
    nc = v & 1
    return ((v >> 1) | (0x80 if carry else 0)), nc


def asr16(v):
    """6809 arithmetic right shift of D implemented as ASRA / RORB."""
    A = hi(v)
    B = lo(v)
    A, c = asr8(A)
    B, _ = ror8(B, c)
    return (A << 8) | B


def sub8(a, b):
    # 6809 subtraction; carry represents borrow.
    a, b = u8(a), u8(b)
    r = a - b
    return u8(r), 1 if r < 0 else 0


def add8(a, b, carry=0):
    r = u8(a) + u8(b) + (1 if carry else 0)
    return u8(r), 1 if r > 0xFF else 0


def advance_depth(depth, speed, subtract=False):
    """
    ROM $0976/$0979.

    The 6809 computes the low-byte product first; MUL places bit 7 of the low
    product into Carry and ADCA #0 rounds the high part. Equivalent:
        delta = (depth * speed + $80) >> 8
    """
    depth &= 0xFFFF
    speed &= 0xFF
    delta = ((depth * speed) + 0x80) >> 8
    return u16(depth - delta if subtract else depth + delta)



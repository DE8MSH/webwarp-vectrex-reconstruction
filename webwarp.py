def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rom")
    ap.add_argument("--vectors")
    ap.add_argument("--bios")
    ap.add_argument(
        "--beam-gain",
        type=float,
        default=1.0,
        help="final analogue display gain only; 1.0 = calibrated V7 default"
    )
    ap.add_argument("--self-test", action="store_true")
    ns = ap.parse_args()

    global HW_TO_PIXELS
    if not (0.5 <= ns.beam_gain <= 2.0):
        raise SystemExit("--beam-gain must be between 0.5 and 2.0")
    HW_TO_PIXELS = BASE_HW_TO_PIXELS * ns.beam_gain

    here = Path(__file__).resolve().parent

    rom = Path(ns.rom) if ns.rom else locate([
        here / "Web Warp (1983).vec",
        Path("/mnt/data/Web Warp (1983).vec"),
    ])

    vectors = Path(ns.vectors) if ns.vectors else locate([
        here / "web_warp_vectors.json",
        here / "web_warp_vectors(1).json",
        Path("/mnt/data/web_warp_vectors.json"),
        Path("/mnt/data/web_warp_vectors(1).json"),
    ])

    bios = Path(ns.bios) if ns.bios else locate([
        here / "Vectrex BIOS (1982)(5).vec",
        here / "Vectrex BIOS (1982).vec",
        Path("/mnt/data/Vectrex BIOS (1982)(5).vec"),
    ])

    if rom is None or not rom.exists():
        raise SystemExit("Web Warp ROM not found")
    if vectors is None or not vectors.exists():
        raise SystemExit("web_warp_vectors.json not found")

    a = Assets(rom, vectors, bios)

    if ns.self_test:
        self_test(a)
        return

    require_pygame()

    pygame.init()
    screen = pygame.display.set_mode((W, H))
    pygame.display.set_caption("Web Warp — Python vector reconstruction V8 — foreground web fixed")
    clock = pygame.time.Clock()

    fonts = (
        pygame.font.Font(None, 62),
        pygame.font.Font(None, 36),
        pygame.font.Font(None, 27),
        pygame.font.Font(None, 19),
    )

    game = Game(a)
    running = True

    try:
        while running:
            for ev in pygame.event.get():
                if ev.type == pygame.QUIT:
                    running = False
                    break
                if not game.handle_event(ev):
                    running = False
                    break

            # Do not execute another potentially expensive update/draw after X.
            if not running:
                break

            keys = pygame.key.get_pressed()
            game.update(keys)

            screen.fill(BLACK)
            game.draw(screen, fonts, keys)
            pygame.display.flip()
            clock.tick(FPS)

    except KeyboardInterrupt:
        pass
    finally:
        pygame.display.quit()
        pygame.quit()


if __name__ == "__main__":
    main()

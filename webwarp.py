class Renderer:
    def __init__(self, surface, biosmath: BiosMath):
        self.s = surface
        self.bm = biosmath

    def line(self, a, b, color=MID, width=1):
        # clipline prevents enormous off-screen coordinates from making SDL's
        # rasterizer unnecessarily expensive and also makes window close robust.
        try:
            ax, ay = float(a[0]), float(a[1])
            bx, by = float(b[0]), float(b[1])
        except (TypeError, ValueError, OverflowError):
            return

        if not all(math.isfinite(v) for v in (ax, ay, bx, by)):
            return

        # Hard sanity guard before integer conversion.
        lim = 1_000_000
        if any(abs(v) > lim for v in (ax, ay, bx, by)):
            return

        clipped = self.s.get_rect().clipline(
            (int(round(ax)), int(round(ay))),
            (int(round(bx)), int(round(by))),
        )
        if clipped:
            if width == 1:
                pygame.draw.aaline(self.s, color, clipped[0], clipped[1], True)
            else:
                pygame.draw.line(self.s, color, clipped[0], clipped[1], width)

    def text(self, font, text, pos, color=MID, center=False):
        img = font.render(text, True, color)
        if center:
            pos = (
                int(pos[0] - img.get_width() / 2),
                int(pos[1] - img.get_height() / 2),
            )
        self.s.blit(img, pos)

    @staticmethod
    def hw_delta(dy, dx, scale):
        """
        Relative Vectrex beam delta -> desktop pixels.
        """
        px = dx * scale * HW_TO_PIXELS
        py = -dy * scale * HW_TO_PIXELS
        return px, py

    def move_pair(self, origin, pair, scale):
        dy, dx = pair
        px, py = self.hw_delta(dy, dx, scale)
        return origin[0] + px, origin[1] + py

    def original_mode_list(self, cmds, origin, scale, angle=0, color=WHITE):
        """
        Render a decoded Web Warp mode list using BIOS-style integer rotation.

        The ROM's vector data are dy/dx relative bytes. Every delta is transformed
        through the same rise/run integer path used by Rot_VL_Mode.
        """
        pos = (float(origin[0]), float(origin[1]))

        for c in cmds:
            dy = s8(c["dy"])
            dx = s8(c["dx"])
            if angle:
                dy, dx = self.bm.rotate_delta(dy, dx, angle)

            nxt = self.move_pair(pos, (dy, dx), scale)
            if c.get("draw"):
                self.line(
                    (int(round(pos[0])), int(round(pos[1]))),
                    (int(round(nxt[0])), int(round(nxt[1]))),
                    color
                )
            pos = nxt

        return pos


